#!/usr/bin/env python3
"""Synthetic loose/ISO fixture exercising the linked original GameSource API.

Only disposable, independently generated byte strings are used. This is not
proof of playability with actual Ravenloft installation assets.
"""
from __future__ import annotations

import argparse
import hashlib
import os
from pathlib import Path
import subprocess
import tempfile

SECTOR = 2048


def record(name: bytes, extent: int, size: int, directory: bool = False) -> bytes:
    length = 33 + len(name) + (not len(name) % 2)
    out = bytearray(length)
    out[0] = length
    out[2:6] = extent.to_bytes(4, "little")
    out[6:10] = extent.to_bytes(4, "big")
    out[10:14] = size.to_bytes(4, "little")
    out[14:18] = size.to_bytes(4, "big")
    out[25] = 2 if directory else 0
    out[28] = out[31] = 1
    out[32] = len(name)
    out[33:33 + len(name)] = name
    return bytes(out)


def make_image(path: Path, user_offset: int = 0, physical_sector: int = SECTOR) -> None:
    sectors = [bytearray(SECTOR) for _ in range(32)]
    primary = sectors[16]
    primary[0:7] = b"\x01CD001\x01"
    primary[156:190] = record(b"\x00", 20, SECTOR, True)
    sectors[17][0:7] = b"\xffCD001\x01"
    root = b"".join([
        record(b"\x00", 20, SECTOR, True),
        record(b"\x01", 20, SECTOR, True),
        record(b"RES0;1", 21, 1),
        record(b"INIT;1", 22, 2),
        record(b"T;1", 23, 3),
        record(b"RES4;1", 24, 3),
    ])
    sectors[20][0:len(root)] = root
    sectors[21][0] = 5
    sectors[22][0:2] = b"\x01\x02"
    sectors[23][0:3] = b"\x03\x04\x05"
    sectors[24][0:3] = b"\x06\x07\x08"
    with path.open("wb") as output:
        for sector in sectors:
            physical = bytearray(physical_sector)
            physical[user_offset:user_offset + SECTOR] = sector
            output.write(physical)


def make_synthetic_res0_cursor() -> bytes:
    # Source-verified INIT[0]=0 selects RES0[0x2F], EH type1 with 8x2 pixels.
    count = 48
    first_offset = 4 + 4 * count
    header = count.to_bytes(4, "little")
    offsets = first_offset.to_bytes(4, "little") * count
    record = bytes([69, 72, 1, 8, 0, 1, 0, 2, 0, 1, 255, 0, 0])
    pixels = bytes([0, 1, 2, 3, 4, 5, 6, 7, 7, 6, 5, 4, 3, 2, 1, 0])
    return header + offsets + record + pixels


def make_synthetic_menu_res0() -> bytes:
    # Original CODE.2 0x192CC static menu draws RES0 indices 97..101.
    # These are synthetic EH type-1 test records, not copyrighted sprites.
    count = 102
    data = bytearray(4 + 4 * count)
    data[0:4] = count.to_bytes(4, "little")
    for i in range(count):
        data[4 + 4*i:8 + 4*i] = len(data).to_bytes(4, "little")
        if 97 <= i <= 101:
            record = bytes([69, 72, 1, 8, 0, 1, 0, 2, 0, 1, 255, 0, 0])
            data.extend(record + bytes([i - 95] * 16))
    return bytes(data)


def run(exe: Path, *args: str, env: dict[str, str] | None = None) -> subprocess.CompletedProcess[str]:
    return subprocess.run([str(exe), *args], env=env, capture_output=True,
                          text=True, check=False, timeout=15)


def expect(result: subprocess.CompletedProcess[str], code: int, needle: str) -> None:
    assert result.returncode == code, (result.args, result.returncode, result.stdout, result.stderr)
    assert needle in result.stdout + result.stderr, (needle, result.stdout, result.stderr)


def snapshot(folder: Path) -> dict[str, str]:
    return {p.relative_to(folder).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in folder.rglob("*") if p.is_file()}


def test(exe: Path, bootstrap: Path | None = None) -> None:
    assert exe.is_file(), exe
    with tempfile.TemporaryDirectory(prefix="rloft-native-install-") as temp:
        root = Path(temp)
        loose = root / "loose"
        loose.mkdir()
        for name, value in {"res0": b"\x05", "INIT": b"\x01\x02",
                            "T": b"\x03\x04\x05", "RES4": b"\x06\x07\x08"}.items():
            (loose / name).write_bytes(value)
        # Windows GUI source renderer diagnostic: both image input and
        # original palette must come from an original-format synthetic RES
        # fixture, not from hardcoded GUI test pixels.
        if bootstrap:
            cursor_dir = root / "source-backed-cursor"
            cursor_dir.mkdir()
            (cursor_dir / "INIT").write_bytes(bytes([0, 0]))
            (cursor_dir / "T").write_bytes(bytes([1]))
            (cursor_dir / "RES0").write_bytes(make_synthetic_res0_cursor())
            palette = bytearray(1 + 15 * 768)
            palette[0] = 15
            palette[1 + 12 * 768 + 3] = 63
            (cursor_dir / "COLORS").write_bytes(palette)
            original_cursor_hashes = snapshot(cursor_dir)
            assert run(bootstrap, "--self-test-source-cursor", str(cursor_dir)).returncode == 0
            assert snapshot(cursor_dir) == original_cursor_hashes
            # Corrupt optional source palette: normal inspect still works,
            # but strict original cursor output must fail, never fake it.
            (cursor_dir / "COLORS").write_bytes(bytes(palette[:-1]))
            assert run(bootstrap, "--self-test-source-cursor", str(cursor_dir)).returncode == 4
            assert run(bootstrap, "--self-test-install", str(cursor_dir)).returncode == 0

            menu_dir = root / "source-backed-static-menu"
            menu_dir.mkdir()
            (menu_dir / "RES0").write_bytes(make_synthetic_menu_res0())
            (menu_dir / "INIT").write_bytes(bytes([0, 0]))
            (menu_dir / "T").write_bytes(bytes([1]))
            (menu_dir / "COLORS").write_bytes(palette)
            for archive_name in ("RES1", "RES5", "RES6", "RES7", "RES8", "RES10"):
                (menu_dir / archive_name).write_bytes(bytes([0, 0, 0, 0]))
            # Mimic the pinned CODE.1 byte length only. Never executable data.
            (menu_dir / "CODE.1").write_bytes(bytes(0x43D1B))
            before_menu = snapshot(menu_dir)
            assert run(bootstrap, "--self-test-source-menu", str(menu_dir)).returncode == 0
            assert snapshot(menu_dir) == before_menu
            # Removing any eagerly loaded original asset disqualifies menu
            # evidence without affecting minimum install detection.
            (menu_dir / "RES5").unlink()
            assert run(bootstrap, "--self-test-source-menu", str(menu_dir)).returncode == 5
            assert run(bootstrap, "--self-test-install", str(menu_dir)).returncode == 0
        before = snapshot(loose)
        expect(run(exe, "--install", str(loose)), 0, "MINIMUM_MEDIA_SIGNATURE_PASS")
        if bootstrap:
            assert run(bootstrap, "--self-test-install", str(loose)).returncode == 0
        out = run(exe, "--install", str(loose)).stdout
        assert "loose Ravenloft media directory" in out
        assert "ASSET\tRES4\tPRESENT\tINVENTORY\t-" in out
        assert "SOURCE_VERSION\tUNVERIFIED" in out
        assert "PLAYABLE_GAME_NOT_YET_IMPLEMENTED" in out
        # Windows wmain must preserve Unicode install paths end-to-end.
        unicode_dir = root / "Ravenloft-Été-中文"
        unicode_dir.mkdir()
        for name in ("RES0", "INIT", "T"):
            (unicode_dir / name).write_bytes(bytes([1, 2, 3]))
        unicode_before = snapshot(unicode_dir)
        expect(run(exe, "--install", str(unicode_dir)), 0, "MINIMUM_MEDIA_SIGNATURE_PASS")
        if bootstrap:
            assert run(bootstrap, "--self-test-install", str(unicode_dir)).returncode == 0
        assert snapshot(unicode_dir) == unicode_before
        env = dict(os.environ, RLOFT_GAME_DIR=str(loose))
        expect(run(exe, "--auto", env=env), 0, "MINIMUM_MEDIA_SIGNATURE_PASS")
        assert snapshot(loose) == before, "inspector modified source installation"
        (loose / "T").write_bytes(b"")
        expect(run(exe, "--install", str(loose)), 3, "MEDIA_INCOMPLETE")
        if bootstrap:
            assert run(bootstrap, "--self-test-install", str(loose)).returncode == 3
        (loose / "T").unlink()
        expect(run(exe, "--install", str(loose)), 2, "MEDIA_PROBE_ERROR")
        expect(run(exe, "--install", str(root / "absent")), 2, "MEDIA_PROBE_ERROR")
        if bootstrap:
            assert run(bootstrap, "--self-test-install", str(root / "absent")).returncode == 2
        expect(run(exe, "--unknown"), 64, "Usage:")
        expect(run(exe, "--help"), 0, "READ ONLY")
        for label, offset, sector_size in [("iso2048", 0, 2048),
                                           ("iso2352mode1", 16, 2352),
                                           ("iso2352mode2", 24, 2352)]:
            folder = root / label
            folder.mkdir()
            image = folder / "game.gog"
            make_image(image, offset, sector_size)
            original_hash = hashlib.sha256(image.read_bytes()).hexdigest()
            result = run(exe, "--install", str(folder))
            expect(result, 0, "MINIMUM_MEDIA_SIGNATURE_PASS")
            if bootstrap:
                assert run(bootstrap, "--self-test-install", str(folder)).returncode == 0
                assert run(bootstrap, "--self-test-install", str(image)).returncode == 0
            assert "installed GOG game.gog CD image" in result.stdout
            assert "ASSET\tRES4\tPRESENT" in result.stdout
            expect(run(exe, "--install", str(image)), 0, "MINIMUM_MEDIA_SIGNATURE_PASS")
            assert hashlib.sha256(image.read_bytes()).hexdigest() == original_hash
        print("INSTALL_PROBE_SYNTHETIC_MEDIA_PASS: loose + ISO2048 + ISO2352(16/24)")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--executable", type=Path, required=True)
    parser.add_argument("--bootstrap", type=Path)
    arguments = parser.parse_args()
    test(arguments.executable.resolve(), arguments.bootstrap.resolve() if arguments.bootstrap else None)
