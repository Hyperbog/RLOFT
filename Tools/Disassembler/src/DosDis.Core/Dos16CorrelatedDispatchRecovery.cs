namespace DosDis.Core;

/// <summary>
/// Correlation of independently source-validated unsigned guard/stride
/// hypotheses with entry-site finite BX byte-offset evidence. Candidate
/// stored pointers do not establish execution or immutable runtime memory.
/// </summary>
public sealed record Dos16CorrelatedDispatchSite(
    Dos16Address Site, string Status, string GuardStatus,
    string? PointerKind, int? GuardedEntryCount,
    IReadOnlyList<int> CandidateIndices,
    IReadOnlyList<Dos16TableEntry> CandidateStoredEntries, string Evidence);

public sealed record Dos16CorrelatedDispatchReport(
    string SourceSha256, string MappingEvidence, string AnalysisStatus,
    bool Incomplete, int InspectedSites, int GuardedStorageSites,
    int BoundedIndexSites, int UnresolvedSites, int CodeDataConflicts,
    IReadOnlyList<Dos16CorrelatedDispatchSite> Sites);

/// <summary>
/// A read-only cross-check, not a new CFG engine. The automatic unsigned
/// compare/Jcc/scale proof supplies the independent table count; the
/// source-backed dataflow pass supplies finite BX byte offsets at the site;
/// the storage validator independently checks every stored pointer.
/// No original bytes, graph edges, or code/data labels are modified.
/// </summary>
public static class Dos16CorrelatedDispatchRecovery
{
    public static Dos16CorrelatedDispatchReport Inspect(
        Dos16CodeRegion region, Dos16FlowResult graph,
        DosMzImage? mz = null, DosMzRebasedView? simulation = null,
        int maximumInstructions = 20_000, int maximumSteps = 100_000,
        int maximumEdges = 80_000)
    {
        ArgumentNullException.ThrowIfNull(region);
        ArgumentNullException.ThrowIfNull(graph);

        Dos16CorrelatedDispatchReport Incomplete(string status) =>
            new(region.SourceSha256, region.MappingEvidence,
                "incomplete;" + status + ";no-CFG-promotion", true,
                0, 0, 0, 0, 0, Array.Empty<Dos16CorrelatedDispatchSite>());

        // A complete independently checked candidate CFG is mandatory
        // before even asking the automatic guard analysis to inspect it.
        // This also rejects externally edited/duplicated graph snapshots.
        var flow = Dos16DataflowAnalysis.Analyze(region, graph,
            maximumInstructions, maximumSteps, maximumEdges);
        if (flow.Incomplete)
            return Incomplete("register-flow-" + flow.AnalysisStatus);

        var guard = Dos16AutomaticDispatchRecovery.Inspect(
            region, graph, mz, simulation);
        if (guard.Truncated)
            return Incomplete("guarded-site-inventory-truncated");
        if (!string.Equals(guard.SourceSha256, region.SourceSha256,
                StringComparison.OrdinalIgnoreCase) ||
            guard.MappingEvidence != region.MappingEvidence ||
            guard.Sites.Count != guard.IndirectSites)
            return Incomplete("guarded-report-identity-or-count-mismatch");

        var accepted = new List<Dos16GuardedDispatchSite>();
        foreach (var site in guard.Sites)
        {
            bool declaredCandidate =
                site.Status == "candidate-guarded-CS-BX-table";
            if (declaredCandidate != (site.StoredTable is not null))
                return Incomplete("guarded-site-status-and-storage-disagree");
            if (site.StoredTable is null) continue;
            if (site.Status != "candidate-guarded-CS-BX-table" ||
                site.PointerKind is not ("near16" or "far16") ||
                site.EntryCount is null or < 2 or > 256 ||
                site.StoredTable.Site != site.Address ||
                site.StoredTable.PointerKind != site.PointerKind ||
                site.StoredTable.RequestedCount != site.EntryCount.Value ||
                site.StoredTable.Status != "candidate-entries-source-backed" ||
                site.StoredTable.Entries.Count != site.EntryCount.Value)
                return Incomplete("guarded-storage-result-inconsistent");
            accepted.Add(site);
        }

        if (guard.GuardedTableCandidates != accepted.Count ||
            guard.UnresolvedSites != guard.IndirectSites - accepted.Count)
            return Incomplete("guarded-candidate-accounting-inconsistent");

        // Bounds are generated by the exact guarded recovery, not inferred
        // from a register constant or a user filename. The legacy manifest
        // validator independently re-checks the count and all pointer bytes.
        Dos16TableIndexEvidenceReport? selected = null;
        if (accepted.Count != 0)
        {
            var tableManifest = new Dos16TableManifest(1,
                region.SourceSha256, accepted.Select(site =>
                    new Dos16TableRequest(
                        site.Address.Offset, site.StoredTable!.Table,
                        site.EntryCount!.Value, site.PointerKind!,
                        "correlated:source-backed-unsigned-guard-and-stride"))
                    .ToArray());
            selected = Dos16TableIndexEvidence.Inspect(
                region, graph, tableManifest, mz, simulation,
                maximumInstructions, maximumSteps, maximumEdges);
            if (selected.Incomplete ||
                selected.Sites.Count != accepted.Count ||
                selected.CandidateSites + selected.UnresolvedSites != accepted.Count ||
                selected.CodeDataConflicts != 0 ||
                !string.Equals(selected.SourceSha256, region.SourceSha256,
                    StringComparison.OrdinalIgnoreCase) ||
                selected.MappingEvidence != region.MappingEvidence)
                return Incomplete("independent-table-index-recheck-incomplete");

            // The second storage pass must still agree with every
            // independently accepted guarded site, its exact table
            // displacement, width, and count. A source/geometry conflict
            // is an integrity failure, not a permission to publish a
            // partial or unverified replacement table.
            var guardedBySite = accepted.ToDictionary(x => x.Address);
            foreach (var index in selected.Sites)
            {
                if (!guardedBySite.TryGetValue(index.Site, out var original) ||
                    index.PointerKind != original.PointerKind ||
                    index.DeclaredEntries != original.EntryCount ||
                    index.Table != original.StoredTable!.Table ||
                    index.StorageValidationStatus !=
                        "candidate-entries-source-backed" ||
                    index.CandidateStoredEntries.Count != index.PossibleIndices.Count ||
                    index.CandidateStoredEntries.Where((entry, i) =>
                        entry.Index != index.PossibleIndices[i]).Any())
                    return Incomplete("independent-table-index-evidence-disagrees");
            }
        }

        var indexBySite = selected?.Sites.ToDictionary(x => x.Site) ??
            new Dictionary<Dos16Address, Dos16TableIndexSiteEvidence>();
        var results = new List<Dos16CorrelatedDispatchSite>();
        int selectedCount = 0, conflicts = 0;
        foreach (var site in guard.Sites)
        {
            if (site.Status == "rejected-guarded-table:rejected-code-data-overlap")
                conflicts++;
            string status = "unresolved-no-source-proven-unsigned-guard-and-stride";
            string evidence = "automatic-guard:" + site.Status +
                ";no-execution-or-runtime-memory-proof";
            IReadOnlyList<int> indices = Array.Empty<int>();
            IReadOnlyList<Dos16TableEntry> entries = Array.Empty<Dos16TableEntry>();
            if (indexBySite.TryGetValue(site.Address, out var index))
            {
                status = index.Status == "candidate-bounded-byte-offset-and-stored-entries"
                    ? "candidate-guarded-and-finite-index-stored-pointers"
                    : "unresolved-guarded-storage-index:" + index.Status;
                evidence = "automatic-guard-and-source-pointer-validation;" +
                    "independent-register-flow:" + index.Evidence +
                    ";no-runtime-table-mutation-proof;no-CFG-promotion";
                if (status == "candidate-guarded-and-finite-index-stored-pointers")
                {
                    selectedCount++;
                    indices = index.PossibleIndices;
                    entries = index.CandidateStoredEntries;
                }
                if (index.StorageValidationStatus == "rejected-code-data-overlap")
                    conflicts++;
            }
            results.Add(new Dos16CorrelatedDispatchSite(site.Address,
                status, site.Status, site.PointerKind, site.EntryCount,
                indices, entries, evidence));
        }

        return new Dos16CorrelatedDispatchReport(
            region.SourceSha256, region.MappingEvidence,
            "candidate-unverified;unsigned-guard-and-finite-index-cross-check;" +
            "runtime-pointer-contents-unknown;no-CFG-or-function-promotion",
            false, results.Count, accepted.Count, selectedCount,
            results.Count - selectedCount, conflicts, results.AsReadOnly());
    }
}
